// Typed wrappers around the server registry Tauri commands (TASK-M1-03/05).
// Mirrors the Rust `ServerEntry` / `ServerEntryInput` / `ServerHealth` shapes
// (camelCase) and normalizes rejections to ApiError, following client.ts.

import { invoke } from "@tauri-apps/api/core";
import { ApiError } from "./errors.js";

/** A saved server connection (mirrors the Rust `ServerEntry`). */
export interface ServerEntry {
  id: string;
  name: string;
  url: string;
  username?: string;
  password?: string;
  oauth?: ServerOAuth;
  /** Whether the desktop app owns the local opencode serve process. */
  mode?: ServerMode;
  createdAt: number;
  lastConnectedAt?: number;
}

export type ServerMode = "remote" | "local";

/** RFC 9728 OAuth credentials stored on a server entry (mirrors the Rust
 *  `ServerOAuth`). Tokens are managed by the Rust side; the frontend only
 *  reads the shape to decide between Basic and OAuth re-auth flows. */
export interface ServerOAuth {
  clientId: string;
  discoveryUrl: string;
  authorizationEndpoint: string;
  tokenEndpoint: string;
  scope?: string;
  accessToken: string;
  refreshToken?: string;
  expiresAt?: number;
}

/** Result of an RFC 9728 discovery (`oauth_discover`). */
export interface OAuthDiscovery {
  authorizationEndpoint: string;
  tokenEndpoint: string;
  clientId?: string;
  scopesSupported?: string[];
}

/** Result of `oauth_authorize`: the URL to open in the system browser. */
export interface OAuthAuthorizeResult {
  authorizationUrl: string;
  redirectUri: string;
  clientId: string;
}

/** Credential state of a server (`oauth_status`). */
export interface OAuthStatus {
  configured: boolean;
  hasRefreshToken: boolean;
}

/** User-supplied fields of a server entry; id and timestamps are generated by the registry. */
export interface ServerEntryInput {
  name: string;
  url: string;
  username?: string;
  password?: string;
  mode?: ServerMode;
}

/** Basic Auth credentials for probes and requests. */
export interface AuthCredentials {
  username?: string;
  password?: string;
}

/** Health snapshot of one server (mirrors the Rust `ServerHealth`). */
export interface ServerHealth {
  serverId: string;
  healthy: boolean;
  version?: string;
  latencyMs?: number;
  lastOk?: number;
  failCount: number;
  status: "ok" | "slow" | "down";
}

export async function listServers(): Promise<ServerEntry[]> {
  return invoke<ServerEntry[]>("list_servers").catch((err: unknown) => {
    throw ApiError.fromUnknown(err);
  });
}

export async function addServer(input: ServerEntryInput): Promise<ServerEntry> {
  return invoke<ServerEntry>("add_server", { entry: input }).catch((err: unknown) => {
    throw ApiError.fromUnknown(err);
  });
}

export async function updateServer(id: string, input: ServerEntryInput): Promise<ServerEntry> {
  return invoke<ServerEntry>("update_server", { id, entry: input }).catch((err: unknown) => {
    throw ApiError.fromUnknown(err);
  });
}

export async function removeServer(id: string): Promise<void> {
  return invoke<void>("remove_server", { id }).catch((err: unknown) => {
    throw ApiError.fromUnknown(err);
  });
}

