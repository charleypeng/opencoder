/** Discovers the RFC 9728 OAuth metadata of a server URL. Rejects with
 *  a not_found ApiError when the server has no discovery document. */
export async function discoverOAuth(url: string): Promise<OAuthDiscovery> {
  return invoke<OAuthDiscovery>("oauth_discover", { url }).catch((err: unknown) => {
    throw ApiError.fromUnknown(err);
  });
}

/** Starts an OAuth authorization for a saved server: generates PKCE +
 *  state (kept in the Rust process), returns the URL to open in the
 *  system browser. The redirect URI is a loopback callback. */
export async function authorizeOAuth(serverId: string): Promise<OAuthAuthorizeResult> {
  return invoke<OAuthAuthorizeResult>("oauth_authorize", { serverId }).catch((err: unknown) => {
    throw ApiError.fromUnknown(err);
  });
}

/** Exchanges the authorization code (from the browser redirect) for
 *  tokens and stores them on the server entry. */
export async function exchangeOAuth(serverId: string, code: string, state: string): Promise<void> {
  return invoke<void>("oauth_exchange", { serverId, code, state }).catch((err: unknown) => {
    throw ApiError.fromUnknown(err);
  });
}

/** Refreshes the server's access token with its stored refresh token. */
export async function refreshOAuth(serverId: string): Promise<void> {
  return invoke<void>("oauth_refresh", { serverId }).catch((err: unknown) => {
    throw ApiError.fromUnknown(err);
  });
}

/** Clears the server's OAuth credentials (logout / re-auth from scratch). */
export async function clearOAuth(serverId: string): Promise<void> {
  return invoke<void>("oauth_clear", { serverId }).catch((err: unknown) => {
    throw ApiError.fromUnknown(err);
  });
}

/** Reads the OAuth credential state of a saved server. */
export async function oauthStatus(serverId: string): Promise<OAuthStatus> {
  return invoke<OAuthStatus>("oauth_status", { serverId }).catch((err: unknown) => {
    throw ApiError.fromUnknown(err);
  });
}
